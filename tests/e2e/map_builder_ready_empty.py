"""Import a finished map and author image-free Smart Objects in a disposable VTT.

The common browser harness owns its campaign, sessions, database, media, server
and artifacts. Every uploaded image is generated by this scenario.
"""
from __future__ import annotations

from copy import deepcopy
from io import BytesIO
import json
import time

import map_builder_blueprints as harness
from map_builder import MEASURE, builder_sidebar, builder_tool, builder_workspace, change_locale
from map_builder_asset_removal import BuilderReview
from map_builder_playtest import behavior, chain, node
from map_builder_reference import close_panel, wait_ready


def ready_map():
    from PIL import Image, ImageDraw

    image = Image.new('RGB', (1280, 640), '#28614b')
    draw = ImageDraw.Draw(image)
    draw.rectangle((32, 32, 224, 224), fill='#983a31')
    draw.rectangle((1056, 416, 1248, 608), fill='#315b99')
    result = BytesIO()
    image.save(result, 'PNG')
    return result.getvalue()


def check_browser(base, seed, output, executable):
    from PIL import Image
    from playwright.sync_api import expect, sync_playwright

    campaign = seed['campaign']
    records, metrics, errors, dialogs, commands, replies = [], [], [], [], [], []
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(**({'executable_path': str(executable)} if executable else {}))
        context = browser.new_context(base_url=base, viewport={'width': 1440, 'height': 900})
        context.add_cookies([{**seed['sessions']['gm'], 'url': base}])
        page = context.new_page()
        player_context = player_page = None

        def observe(target):
            target.on('pageerror', lambda error: errors.append(str(error)))
            target.on('dialog', lambda dialog: (dialogs.append(dialog.message), dialog.dismiss()))

            def websocket(connection):
                def sent(payload):
                    if not isinstance(payload, str):
                        return
                    value = json.loads(payload)
                    data = value.get('payload', {}).get('data', {})
                    if value.get('type') == 'maps.command' and data.get('area') == 'images' and data.get('action') == 'interact':
                        commands.append(value)

                def received(payload):
                    if isinstance(payload, str):
                        value = json.loads(payload)
                        if value.get('type') in ('maps.ack', 'maps.error'):
                            replies.append(value)

                connection.on('framesent', sent)
                connection.on('framereceived', received)

            target.on('websocket', websocket)

        observe(page)
        review = BuilderReview(page, campaign)

        def saved():
            expect(page.locator('[data-map-builder]')).to_have_attribute('data-save-state', 'saved', timeout=20_000)
            identifier = page.evaluate("new URL(location.href).searchParams.get('project')")
            assert identifier
            return review.project(identifier)

        def game(target=page):
            target.wait_for_url(f'{base}/game/{campaign}')
            target.wait_for_function('!!window.gravewrightMaps?.current && !!window.gravewrightRealtime')
            expect(target.locator('.game-menubar__presence')).to_have_attribute('data-presence', 'seated')

        def native(target=page):
            response = target.request.get(f'/api/maps/{scene_id}/state')
            assert response.ok, response.text()
            return response.json()

        def native_point(target, image):
            target.wait_for_function('!!gravewrightMaps.board?.viewport()')
            return target.evaluate('''image=>{
                const surface=document.querySelector('.game-board__surface').getBoundingClientRect(),view=gravewrightMaps.board.viewport();
                return {x:surface.x+view.x+image.x*view.scale,y:surface.y+view.y+image.y*view.scale};
            }''', image)

        def interact(target, image, expected):
            before = len(commands)
            point = native_point(target, image)
            target.mouse.dblclick(point['x'], point['y'], delay=70)
            deadline = time.monotonic() + 12
            acknowledgement = None
            while time.monotonic() < deadline:
                if len(commands) > before:
                    identifier = commands[-1]['payload']['requestId']
                    acknowledgement = next((value for value in replies
                                            if value['payload'].get('requestId') == identifier), None)
                    if acknowledgement:
                        break
                target.wait_for_timeout(50)
            assert len(commands) == before + 1 and acknowledgement, {'commands': commands, 'replies': replies, 'point': point}
            assert acknowledgement['type'] == 'maps.ack', acknowledgement
            current = next(row for row in native(target)['images'] if row.get('empty'))
            assert current['lever']['state'] == expected and current['asset_id'] is None and current['src'] == '', current
            return current

        try:
            page.goto(review.builder)
            wait_ready(page)
            page.locator('[data-builder-quick-name]').fill('Synthetic imported map with image-free controls')
            page.locator('[data-builder-quick-name]').press('Tab')
            builder_sidebar(page, 'settings')
            page.locator('[data-builder-ready-map]:visible').click()
            modal = page.locator('[data-builder-map-import-modal]')
            expect(modal).to_be_visible()
            expect(page.locator('dialog')).to_have_count(0)
            page.evaluate('''()=>{
                window.__readyMapBitmap=createImageBitmap;
                window.createImageBitmap=(...args)=>__readyMapBitmap(...args).then(async bitmap=>{
                    await new Promise(resolve=>window.__releaseReadyMapBitmap=resolve);return bitmap;
                });
            }''')
            modal.locator('[data-builder-map-upload]').set_input_files({
                'name': 'Synthetic finished map with a deliberately long authored filename.png',
                'mimeType': 'image/png', 'buffer': ready_map(),
            })
            modal.locator('[name=columns]').fill('20')
            modal.locator('[name=rows]').fill('10')
            modal.locator('[name=cellSize]').fill('64')
            page.wait_for_function("typeof window.__releaseReadyMapBitmap==='function'")
            page.evaluate('''async()=>{
                __releaseReadyMapBitmap();window.createImageBitmap=__readyMapBitmap;
                delete window.__readyMapBitmap;delete window.__releaseReadyMapBitmap;
                await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
            }''')
            expect(modal.locator('[name=columns]')).to_have_value('20')
            expect(modal.locator('[name=rows]')).to_have_value('10')
            expect(modal.locator('[name=cellSize]')).to_have_value('64')
            records.append({'case': 'slow-map-image-decoding-cannot-overwrite-grid-values-edited-by-the-user'})
            modal.locator('[data-builder-map-import-submit]').click()
            expect(modal).to_have_count(0)
            wait_ready(page)
            imported = saved()
            background_id = imported['document']['backgroundImage']['assetId']
            assert imported['document']['columns'] == 20 and imported['document']['rows'] == 10, imported
            assert imported['document']['cellSize'] == 64, imported
            expect(page.locator('[data-builder-background-image] image')).to_have_attribute('href', f'/game/map-assets/{background_id}')
            records.append({'case': 'finished-map-uploads-as-background-with-explicit-grid-and-autosave'})

            builder_sidebar(page, 'tools')
            page.locator('[data-builder-empty-object]:visible').click()
            review.stroke((8, 4), (10, 6))
            authored = saved()
            empty, = authored['document']['decorations']
            owner_id = empty['id']
            assert empty['empty'] is True and empty['assetId'] is None and empty['lever']['state'] == 'off', empty
            expect(page.locator(f'[data-object-id="{owner_id}"][data-builder-empty-marker]')).to_be_visible()
            builder_sidebar(page, 'selection')
            expect(page.locator('[data-builder-property=assetId]:visible')).to_have_count(0)
            page.locator('[data-builder-property=name]').fill('Invisible encounter controller with a long descriptive name')
            page.locator('[data-builder-property=name]').press('Tab')
            close_panel(page)
            authored = saved()
            assert authored['document']['decorations'][0]['name'].startswith('Invisible encounter controller'), authored
            records.append({'case': 'empty-object-places-renames-and-saves-without-an-image-attachment'})

            builder_sidebar(page, 'settings')
            page.locator('[data-builder-ready-map]:visible').click()
            importing = page.locator('[data-builder-map-import-modal]')
            importing.locator('[data-builder-map-asset]').select_option(background_id)
            importing.locator('[name=columns]').fill('5')
            importing.locator('[name=rows]').fill('5')
            importing.locator('[data-builder-map-import-submit]').click()
            expect(importing.locator('[role=alert]')).to_be_visible()
            expect(importing).to_be_visible()
            assert saved()['document'] == authored['document']
            importing.locator('[data-builder-map-import-cancel]').click()
            records.append({'case': 'shrinking-the-imported-map-cannot-discard-an-existing-empty-object'})

            page.locator('[data-builder-background-remove]').click()
            detached = saved()['document']
            assert 'backgroundImage' not in detached and detached['decorations'] == authored['document']['decorations']
            page.locator('[data-builder-undo]').click()
            assert saved()['document'] == authored['document']
            page.locator('[data-builder-redo]').click()
            assert saved()['document'] == detached
            page.locator('[data-builder-undo]').click()
            assert saved()['document'] == authored['document']
            close_panel(page)
            records.append({'case': 'background-removal-undo-and-redo-preserve-the-empty-object-and-its-name'})

            builder_tool(page, 'select')
            builder_workspace(page)
            page.locator(f'[data-builder-decorations] [data-object-id="{owner_id}"]').dblclick()
            editor = page.locator('[data-smart-object-modal]')
            expect(editor).to_be_visible()
            expect(editor.locator('[data-blueprint-asset]:visible')).to_have_count(0)
            expect(editor.locator('[data-blueprint-appearance]:visible')).to_have_count(0)
            expect(editor.locator('[data-blueprint-event="interact"]')).to_be_visible()
            expect(editor.locator('[data-blueprint-event="destroy"]')).to_be_visible()
            editor.locator('[data-blueprint-add]').click()
            expect(editor.locator('[data-blueprint-pick-type=sprite]')).to_be_visible()
            expect(editor.locator('[data-blueprint-pick-type=sprite]')).to_be_enabled()
            page.keyboard.press('Escape')
            editor.locator('[data-blueprint-close]').click()
            authored = saved()
            records.append({'case': 'empty-object-opens-the-complete-smart-object-editor-without-an-appearance-picker'})

            builder_tool(page, 'light')
            review.stroke((15, 6), (15, 6))
            authored = saved()
            document = deepcopy(authored['document'])
            lamp, = document['lights']
            lamp['enabled'] = False
            owner = next(row for row in document['decorations'] if row['id'] == owner_id)
            graph = {'nodes': [node('event', 'event', event='interact'), node('check', 'condition', state='off'),
                node('on', 'state', targetState='on'), node('lightOn', 'emitEvent', scope='element', name='LightOn'),
                node('off', 'state', targetState='off'), node('lightOff', 'emitEvent', scope='element', name='LightOff')],
                'edges': [
                    {'kind': 'execution', 'from': 'event', 'to': 'check', 'output': 'next'},
                    {'kind': 'execution', 'from': 'check', 'to': 'on', 'output': 'true'},
                    {'kind': 'execution', 'from': 'on', 'to': 'lightOn', 'output': 'next'},
                    {'kind': 'execution', 'from': 'check', 'to': 'off', 'output': 'false'},
                    {'kind': 'execution', 'from': 'off', 'to': 'lightOff', 'output': 'next'},
                ]}
            owner['blueprint'] = behavior('lever', {'interact': graph,
                'signal:LightOn': chain('signal:LightOn', [node('light', 'light', targetId=lamp['id'], enabled=True)]),
                'signal:LightOff': chain('signal:LightOff', [node('light', 'light', targetId=lamp['id'], enabled=False)]),
            })
            authored = review.store(authored['id'], authored['version'], authored['folderId'], document)
            page.goto(review.builder + '?project=' + authored['id'])
            wait_ready(page)
            assert saved()['document'] == authored['document']
            expect(page.locator('[data-builder-background-image] image')).to_have_count(1)
            expect(page.locator('[data-builder-empty-marker]')).to_have_count(1)
            records.append({'case': 'background-empty-object-and-connected-light-graph-survive-reopening'})

            for locale in ('en', 'pt-BR', 'es'):
                change_locale(page, locale, campaign)
                page.reload()
                wait_ready(page)
                for width, height in ((1440, 900), (390, 844)):
                    page.set_viewport_size({'width': width, 'height': height})
                    builder_sidebar(page, 'tools')
                    empty_button = page.locator('[data-builder-empty-object]:visible')
                    empty_button.scroll_into_view_if_needed()
                    expect(empty_button).to_have_text({'en': 'Empty Object', 'pt-BR': 'Objeto vazio', 'es': 'Objeto vacío'}[locale])
                    measurement = page.locator('[data-map-builder]').evaluate(MEASURE)
                    metrics.append({'locale': locale, 'width': width, **measurement})
                    assert not measurement['tiny'] and not measurement['overflow'], measurement
                    page.screenshot(path=str(output / f'empty-tools-{locale}-{width}.png'))
                    close_panel(page)
                    records.append({'case': 'localized-empty-object-controls-fit-desktop-and-mobile', 'locale': locale, 'width': width})
                    builder_sidebar(page, 'settings')
                    page.locator('[data-builder-ready-map]:visible').click()
                    importing = page.locator('[data-builder-map-import-modal]')
                    importing.locator('[data-builder-map-asset]').select_option(background_id)
                    measurement = importing.evaluate(MEASURE)
                    metrics.append({'locale': locale, 'width': width, 'modal': True, **measurement})
                    assert not measurement['tiny'] and not measurement['overflow'], measurement
                    page.screenshot(path=str(output / f'finished-map-import-{locale}-{width}.png'))
                    importing.locator('[data-builder-map-import-cancel]').click()
                    close_panel(page)
                    assert saved()['document'] == authored['document']
                    records.append({'case': 'localized-map-import-fits-and-cancel-keeps-the-background-and-authored-content', 'locale': locale, 'width': width})
            page.set_viewport_size({'width': 1440, 'height': 900})
            change_locale(page, 'en', campaign)
            builder_workspace(page)
            page.screenshot(path=str(output / 'finished-map-and-empty-object.png'))
            with page.expect_response(lambda response: response.url.endswith('/generate')) as generated:
                page.locator('[data-builder-generate]').click()
            assert generated.value.ok, generated.value.text()
            game()
            authored = review.project(authored['id'])
            scene_id = authored['sceneId']
            current = next(row for row in native()['images'] if row.get('empty'))
            assert current['src'] == '' and current['asset_id'] is None, current
            assert current['layer'] == current['lever']['baseLayer'] == 'gm-image-layer', current
            page.locator('.game-menubar__layer').get_by_text('Game', exact=True).click()
            expect(page.locator(f'[data-smart-image-id="{current["id"]}"]')).to_have_count(0)
            page.locator('.game-menubar__layer').get_by_text('GM', exact=True).click()
            current = interact(page, current, 'on')
            assert native()['lights'][0]['enabled'] is True
            current = interact(page, current, 'off')
            assert native()['lights'][0]['enabled'] is False
            records.append({'case': 'real-gm-double-clicks-run-state-and-light-actions-without-adding-artwork'})
            runs = page.request.get(f'/api/maps/{scene_id}/automation').json()['runs']
            assert [event['event'] for event in runs[0]['events']] == ['interact', 'signal:LightOff'], runs[0]
            records.append({'case': 'empty-object-executes-its-authored-named-signal-and-light-action-after-an-interaction'})

            pixels = Image.open(BytesIO(page.screenshot())).convert('RGB')
            samples = []
            for x, y, expected in ((96, 96, (152, 58, 49)), (1120, 544, (49, 91, 153))):
                point = native_point(page, {'x': x, 'y': y})
                actual = pixels.getpixel((round(point['x']), round(point['y'])))
                assert max(abs(left - right) for left, right in zip(actual, expected)) < 20, {'point': point, 'actual': actual, 'expected': expected}
                samples.append({'point': point, 'actual': actual, 'expected': expected})
            records.append({'case': 'the-generated-scene-renders-both-distinct-parts-of-the-uploaded-background', 'samples': samples})

            page.locator('.game-menubar__layer').nth(5).click()
            page.locator('[data-dock-tool=automation]').click()
            page.locator('[data-automation-view=doors]').click()
            controls = page.locator('[data-scene-controls]')
            controls.locator('[data-scene-controls-type]').select_option('empty')
            expect(controls.locator('[data-scene-controls-element]')).to_have_count(1)
            controls.locator(f'[data-scene-controls-element="{current["id"]}"]').click()
            expect(controls.locator('[data-scene-controls-inspector]')).to_contain_text('Empty Object')
            expect(controls.locator('[data-scene-controls-material]')).to_have_count(0)
            controls.locator('[data-scene-controls-edit]').click()
            editor = page.locator('[data-smart-object-modal]')
            expect(editor).to_be_visible()
            expect(editor.locator('[data-blueprint-appearance]:visible')).to_have_count(0)
            expect(editor.locator('[data-blueprint-instance-name]')).to_contain_text('Invisible encounter controller')
            editor.locator('[data-blueprint-add]').click()
            expect(editor.locator('[data-blueprint-pick-type=sprite]')).to_be_visible()
            expect(editor.locator('[data-blueprint-pick-type=sprite]')).to_be_enabled()
            editor.locator('[data-blueprint-picker-cancel]').click()
            editor.locator('[data-blueprint-close]').click()
            page.locator('[data-network-close]').click()
            page.keyboard.press('Escape')
            page.locator('.game-menubar__layer').get_by_text('Game', exact=True).click()
            records.append({'case': 'live-game-controls-edit-empty-object-with-image-actions-and-no-own-appearance-picker'})

            page.evaluate('''args=>gravewrightRealtime.mapCommand('update',{
                mapId:args.scene,version:args.version,settings:{visibility:'players'}})''',
                {'scene': scene_id, 'version': authored['sceneVersion']})
            page.evaluate("scene=>gravewrightRealtime.mapCommand('activate',{mapId:scene})", scene_id)
            player_context = browser.new_context(base_url=base, viewport={'width': 1440, 'height': 900})
            player_context.add_cookies([{**seed['sessions']['player'], 'url': base}])
            player_page = player_context.new_page()
            observe(player_page)
            player_page.goto(f'/game/{campaign}')
            game(player_page)
            player_page.wait_for_function('scene=>gravewrightMaps.current.id===scene', arg=scene_id)
            assert all(not row.get('empty') for row in native(player_page)['images'])
            expect(player_page.locator('[data-smart-image-id]')).to_have_count(0)
            point = native_point(player_page, current)
            player_page.mouse.move(1, 1)
            player_page.screenshot(path=str(output / 'native-player-no-empty-artwork.png'))
            page.locator('.game-menubar__layer').get_by_text('GM', exact=True).click()
            page.mouse.move(1, 1)
            page.screenshot(path=str(output / 'native-gm-empty-marker.png'))
            gm_point = native_point(page, current)
            gm_pixel = Image.open(output / 'native-gm-empty-marker.png').convert('RGB').getpixel((round(gm_point['x']), round(gm_point['y'])))
            player_pixel = Image.open(output / 'native-player-no-empty-artwork.png').convert('RGB').getpixel((round(point['x']), round(point['y'])))
            assert gm_pixel[0] > player_pixel[0] + 25, {'gm': gm_pixel, 'player': player_pixel}
            records.append({'case': 'the-native-empty-object-marker-is-visible-to-the-gm-and-absent-from-the-player-frame',
                            'gmPixel': gm_pixel, 'playerPixel': player_pixel})
            before = len(commands)
            player_page.mouse.dblclick(point['x'], point['y'], delay=70)
            player_page.wait_for_timeout(250)
            assert len(commands) == before, commands
            assert next(row for row in native()['images'] if row['id'] == current['id'])['lever']['state'] == 'off'
            refused = player_page.evaluate('''async args=>{
              try {await gravewrightRealtime.mapCommand('objects',{mapId:args.scene,area:'images',
                action:'interact',data:{image_id:args.id}});return {accepted:true};}
              catch(error){return {accepted:false,code:error.code,message:error.message};}
            }''', {'scene': scene_id, 'id': current['id']})
            assert refused == {'accepted': False, 'code': 'invalid_input',
                               'message': 'This lever cannot be used.'}, refused
            assert next(row for row in native()['images'] if row['id'] == current['id'])['lever']['state'] == 'off'
            assert native()['lights'][0]['enabled'] is False
            records.append({'case': 'players-receive-no-empty-data-hit-target-or-direct-interaction-permission'})
            current = interact(page, current, 'on')
            assert native(player_page)['lights'][0]['enabled'] is True
            runs = page.request.get(f'/api/maps/{scene_id}/automation').json()['runs']
            assert [event['event'] for event in runs[0]['events']] == ['interact', 'signal:LightOn'], runs[0]
            records.append({'case': 'gm-only-interaction-with-hidden-controller-still-updates-player-visible-light', 'point': point})
        except Exception:
            page.screenshot(path=str(output / 'failure.png'), full_page=True)
            (output / 'diagnostics.json').write_text(json.dumps({'cases': records, 'metrics': metrics,
                'commands': commands, 'replies': replies, 'pageErrors': errors}, indent=2), encoding='utf-8')
            raise
        finally:
            if player_context:
                player_context.close()
            context.close()
            browser.close()
    assert not errors, errors
    assert not dialogs, dialogs
    return {'passed': True, 'cases': records, 'metrics': metrics, 'pageErrors': errors,
            'nativeDialogs': dialogs, 'assets': 'A generated two-to-one PNG; no operator artwork.'}


if __name__ == '__main__':
    harness.check_browser = check_browser
    harness.main()
